  await front.locator('.ic-edited-image-paint canvas').waitFor()
  await browse.click()
  await pile.getByRole('button', { name: 'Fan Out', exact: true }).click()
  await browse.click()
  await pile.getByRole('button', { name: 'Restack', exact: true }).click()
  await browse.click()
  await pile.getByRole('button', { name: 'Unstack All', exact: true }).click()
  await browse.waitFor({ state: 'hidden' })
  await save()
  const reader = await context.newPage()
  await reader.goto(url)
  await reader.getByRole('button', { name: 'Enable editing' }).waitFor()
  assert.equal(await reader.getByRole('region', { name: 'Image Tools' }).count(), 0)
  const rejected = await reader.evaluate(async projectId => {
    const { getProjects, saveProjects } = await import('/src/features/icanvas/storage.ts')
    const project = (await getProjects()).find(item => item.id === projectId)
    try {
      await saveProjects([{ ...project, swatches: [{ id: 'reader', name: 'Reader', colour: '#ff0000' }],
        objects: project.objects.map(object => ({ ...object, imageEdits: undefined })) }]); return false
    }
    catch (error) { return /read-only/i.test(String(error)) }
  }, fixture.project)
  assert.equal(rejected, true)
  await reader.close()
  await page.reload()
  await front.locator('.ic-edited-image-paint canvas').waitFor()
  const reopened = await read()
  assert.deepEqual(object(reopened, fixture.front).imageEdits, edit)
  assert.equal(object(reopened, fixture.front).back.imageEdits.tone.brightness, -28)
  assert.equal(reopened.hash, fixture.hash)

  await front.click({ position: { x: 68, y: 73 } })
  await shortcut('Adjust').click()
  await page.evaluate(id => {
    const put = IDBObjectStore.prototype.put
    window.restoreTestPut = () => { IDBObjectStore.prototype.put = put }
    IDBObjectStore.prototype.put = function (value, ...args) {
      if (this.name === 'projects' && value.id === id) throw new DOMException('Synthetic image-edit save fault', 'QuotaExceededError')
      return put.call(this, value, ...args)
    }
  }, fixture.project)
  await number('Brightness', -49)
  await page.keyboard.press('Control+s')
  await button('Save menu').getByText('Save failed', { exact: true }).waitFor()
  assert.equal(Number(await field('Brightness').inputValue()), -49)
  assert.equal(object(await read(), fixture.front).back.imageEdits.tone.brightness, -28)
  await page.evaluate(() => window.restoreTestPut())
  await button('Retry').first().click()
  await button('Save menu').getByText('Saved', { exact: true }).waitFor()
  assert.equal(object(await read(), fixture.front).back.imageEdits.tone.brightness, -49)

  await button('Save menu').click()
  await button('Save VC').click()
  const checkpoint = page.getByRole('dialog', { name: 'Save VC' })
  await checkpoint.getByLabel('Version notes (optional)').fill('Edited image checkpoint')
  await checkpoint.getByRole('button', { name: 'Save version', exact: true }).click()
  await checkpoint.waitFor({ state: 'hidden' })
  await front.click({ position: { x: 68, y: 73 } })
  await shortcut('Adjust').click()
  await number('Brightness', 35)
  await save()
  await button('Project menu').click()
  await button('Version History').click()
  const history = page.getByRole('dialog', { name: 'Version history' })
  await history.getByRole('button', { name: /v1.*Edited image checkpoint/ }).click()
  await history.getByRole('button', { name: 'Restore…', exact: true }).click()
  await history.getByRole('button', { name: 'Confirm restore', exact: true }).click()
  await history.waitFor({ state: 'hidden' })
