  const front = item(fixture.front)
  await front.locator('img').waitFor()
  await front.click({ position: { x: 80, y: 70 } })
  await imageTools.waitFor()
  await capture('before')
  const original = await read()
  const initialBounds = await front.boundingBox()
  const shortcut = name => page.getByRole('toolbar', { name: 'Selection actions' }).getByRole('button', { name, exact: true })
  await shortcut('Crop').click()
  const crop = page.getByRole('dialog', { name: 'Crop & Straighten' })
  await crop.getByLabel('Crop aspect ratio').selectOption('1:1')
  await crop.getByRole('button', { name: 'Bottom right crop handle' }).press('ArrowLeft')
  await crop.getByRole('button', { name: 'Cancel', exact: true }).click()
  await crop.waitFor({ state: 'hidden' })
  assert.equal(await button('Undo').isDisabled(), true)

