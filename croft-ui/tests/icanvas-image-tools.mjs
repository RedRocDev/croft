  const bothFaces = await read()
  assert.deepEqual(object(bothFaces, fixture.front).imageEdits, edit)
  assert.equal(object(bothFaces, fixture.front).back.imageEdits.tone.brightness, -28)
  assert.equal(object(bothFaces, fixture.direct).imageEdits, undefined)
  assert.equal(bothFaces.hash, fixture.hash)

  await imageTools.getByRole('button', { name: 'Reset All Image Edits', exact: true }).click()
  await front.locator('.ic-card-back img').waitFor()
  await button('Undo').click()
  await front.locator('.ic-edited-image-paint canvas').waitFor()
  await item(fixture.direct).click()
  await shortcut('Adjust').click()
  await number('Contrast', 29)
  await item(fixture.direct).locator('.ic-edited-image-paint canvas').waitFor()
  const useSwatch = () => inspector.getByRole('button', { name: 'Use swatch Sampled study', exact: true }).click()
  await item(fixture.text).click()
  await useSwatch()
  await item(fixture.note).click()
  await useSwatch()
  await item(fixture.stroke).click({ position: { x: 24, y: 32 } })
  await useSwatch()
  const edgePoint = await page.locator('g[data-edge-kind="connection"] .ic-edge-hit').evaluate(line => {
    const x = (line.x1.baseVal.value + line.x2.baseVal.value) / 2
    const y = (line.y1.baseVal.value + line.y2.baseVal.value) / 2
    const screen = new DOMPoint(x, y).matrixTransform(line.getScreenCTM())
    return { x: screen.x, y: screen.y }
  })
  await page.mouse.click(edgePoint.x, edgePoint.y)
  await useSwatch()
  await save()
