  await saveAs.waitFor({ state: 'hidden' })
  await page.getByRole('navigation', { name: 'Canvas breadcrumbs' }).getByText('Independent image tools copy', { exact: true }).waitFor()
  const details = page.getByRole('dialog', { name: 'Project Details' })
  if (await details.count()) await details.getByRole('button', { name: 'Cancel', exact: true }).click()
  const copy = await page.evaluate(async () => {
    const { getProjects } = await import('/src/features/icanvas/storage.ts')
    return (await getProjects()).find(project => project.id === location.hash.split('/')[1])
  })
  const copiedCard = copy.objects.find(object => object.kind === 'image' && object.mode === 'card')
  assert.notEqual(copiedCard.id, fixture.front)
  assert.deepEqual(copiedCard.imageEdits, edit)
  assert.equal(copiedCard.back.imageEdits.tone.brightness, -49)
  assert.deepEqual(copy.swatches, recoloured.project.swatches)
  assert.equal(copiedCard.assetId, fixture.asset)
  await item(copiedCard.id).click({ position: { x: 68, y: 73 } })
  await shortcut('Adjust').click()
  await number('Brightness', 12)
  await save()
  assert.equal(object(await read(), fixture.front).back.imageEdits.tone.brightness, -49)
  assert.deepEqual(errors, [])
  console.log(`Chrome ${browser.version()} passed fixed-ratio crop and cancel on a rotated framed card, independent Back, drag undo, all tone settings, Looks, mask, outline/shadow, compare, sampling and swatch reuse, stack transitions, read-only, quota retry, reload, Save VC, Save As and source SHA-256.`)
