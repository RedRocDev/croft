  assert.equal(object(recoloured, fixture.text).textColour, colour)
  assert.equal(object(recoloured, fixture.note).colour, colour)
  assert.equal(object(recoloured, fixture.stroke).colour, colour)
  assert.equal(recoloured.project.edges[0].colour, colour)
  assert.equal(object(recoloured, fixture.direct).imageEdits.tone.contrast, 29)
  assert.equal(recoloured.other.swatches, undefined)
  assert.equal(recoloured.project.swatches[0].name, 'Sampled study')

