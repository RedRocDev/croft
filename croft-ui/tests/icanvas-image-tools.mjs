  await crop.getByLabel('Crop aspect ratio').selectOption('16:9')
  await crop.getByLabel('Aspect orientation').selectOption('portrait')
  const handle = crop.getByRole('button', { name: 'Bottom right crop handle' })
  const corner = await handle.boundingBox()
  await page.mouse.move(corner.x + corner.width / 2, corner.y + corner.height / 2)
  await page.mouse.down()
  await page.mouse.move(corner.x - 28, corner.y - 16, { steps: 8 })
  await page.mouse.up()
  await crop.getByLabel('Angle (°)').fill('11')
  await crop.getByRole('button', { name: 'Apply Crop', exact: true }).click()
  await crop.waitFor({ state: 'hidden' })
  const picture = front.locator('.ic-edited-image-paint canvas')
  await picture.waitFor()
  assert.deepEqual(await front.boundingBox(), initialBounds)
  await save()
  const cropped = object(await read(), fixture.front)
  assert.equal(cropped.imageEdits.straighten, 11)
  assert.ok(Math.abs(cropped.imageEdits.crop.width * 480 / (cropped.imageEdits.crop.height * 320) - 9 / 16) < 1e-7)
  assert.equal(cropped.rotation, 12)
  assert.equal(cropped.parentId, object(original, fixture.front).parentId)

  await shortcut('Adjust').click()
  const brightness = imageTools.getByRole('slider', { name: 'Brightness', exact: true })
  const slider = await brightness.boundingBox()
  await page.mouse.move(slider.x + slider.width / 2, slider.y + slider.height / 2)
  await page.mouse.down()
  await page.mouse.move(slider.x + slider.width * .9, slider.y + slider.height / 2, { steps: 12 })
  await page.mouse.up()
  const afterDrag = Number(await field('Brightness').inputValue())
  assert.ok(afterDrag > 10, 'Brightness did not respond to the slider drag')
  await button('Undo').click()
  assert.equal(Number(await field('Brightness').inputValue()), 0)
  await button('Redo').click()
  assert.equal(Number(await field('Brightness').inputValue()), afterDrag)
  for (const [label, value] of [['Contrast', 15], ['Saturation', 22], ['Warmth', 30], ['Tint', -17]]) await number(label, value)
  await imageTools.getByRole('button', { name: 'Reset Tint', exact: true }).click()
  assert.equal(Number(await field('Tint').inputValue()), 0)
  await number('Tint', -17)

  await imageTools.getByRole('button', { name: 'Looks', exact: true }).click()
  await imageTools.getByRole('button', { name: 'Sepia', exact: true }).click()
  await number('Look intensity', 65)
  await imageTools.getByRole('button', { name: 'Crop & Shape', exact: true }).click()
  await imageTools.getByLabel('Shape mask').selectOption('circle')
  await number('Image position X', 25)
  await shortcut('Effects').click()
  await imageTools.getByRole('checkbox', { name: 'Outline', exact: true }).check()
  await number('Outline thickness', 7)
  await imageTools.getByRole('checkbox', { name: 'Shadow', exact: true }).check()
  await number('Shadow offset X', 30)
  await number('Shadow offset Y', -12)
  await number('Shadow softness', 18)
  await imageTools.getByRole('button', { name: 'Colours', exact: true }).click()
  await imageTools.getByRole('button', { name: 'Sample colour', exact: true }).click()
  const sample = imageTools.getByRole('button', { name: 'Sample from edited image', exact: true })
  await sample.click({ position: { x: 2, y: 2 } })
  await imageTools.getByText(/That point is transparent/).waitFor()
  await sample.click()
  await sample.press('Enter')
  await imageTools.getByText(/Sampled #[\da-f]{6}/i).waitFor()
  await sample.press('Escape')
  await sample.waitFor({ state: 'hidden' })
  const colour = await imageTools.getByLabel('HEX').inputValue()
  assert.match(colour, /^#[\da-f]{6}$/i)
  await imageTools.getByLabel('Swatch name').fill('Sampled neutral')
  await imageTools.getByRole('button', { name: 'Add swatch', exact: true }).click()
  const swatchName = imageTools.getByRole('textbox', { name: 'Rename Sampled neutral', exact: true })
  await swatchName.fill('Sampled study')
  await swatchName.press('Enter')
  await imageTools.getByRole('button', { name: 'Remove Sampled study', exact: true }).click()
  await button('Undo').click()
  await imageTools.getByRole('button', { name: 'Use Sampled study', exact: true }).waitFor()
  await shortcut('Effects').click()
  await imageTools.getByLabel('Outline colour swatch').selectOption({ label: 'Sampled study' })
  await imageTools.getByLabel('Shadow colour swatch').selectOption({ label: 'Sampled study' })
  await save()
  const edited = object(await read(), fixture.front)
  const edit = edited.imageEdits
  assert.equal(edit.look.name, 'sepia')
  assert.equal(edit.look.intensity, 65)
  assert.equal(edit.mask.shape, 'circle')
  assert.equal(edit.outline.width, 7)
  assert.equal(edit.shadow.x, 30)
  assert.equal(edit.shadow.y, -12)
  const editedPicture = await pixelFingerprint(picture)
  await capture('after')
  const compare = imageTools.getByRole('button', { name: 'Compare Original', exact: true })
  await compare.press('Enter')
  await page.waitForFunction(({ id, previous }) => document.querySelector(`[data-testid="canvas-object-${id}"] .ic-edited-image-paint canvas`)?.toDataURL() !== previous,
    { id: fixture.front, previous: editedPicture })
  assert.deepEqual(object(await read(), fixture.front), edited)
  await compare.press('Enter')
  await page.waitForFunction(({ id, previous }) => document.querySelector(`[data-testid="canvas-object-${id}"] .ic-edited-image-paint canvas`)?.toDataURL() === previous,
    { id: fixture.front, previous: editedPicture })
  await button('Undo').click()
