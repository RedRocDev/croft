const errors = []
const button = (root, name) => root.getByRole('button', { name, exact: true })
const popup = (page, name) => page.getByRole('dialog', { name, exact: true })
const note = page => page.locator('[data-kind="note"][aria-label="The plan"]')
const inspector = page => page.getByRole('complementary', { name: 'Canvas inspector' })
const flip = (item, to) => button(item, 'Show ' + to + ' of card')
const geometry = item => item.evaluate(element => {
  const { left, top, width, height, transform } = element.style
  return { left, top, width, height, transform }
})
const sides = async (item, side) => {
  await flip(item, side === 'front' ? 'back' : 'front').waitFor()
  assert.equal(await item.getAttribute('data-card-side'), side)
}

async function open(context) {
  const page = await context.newPage()
  page.setDefaultTimeout(8_000)
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`) })
  page.on('request', request => {
    if (/^https?:/.test(request.url()) && new URL(request.url()).origin !== url.origin) errors.push(request.url())
  })
  await page.goto(url.href, { waitUntil: 'networkidle' })
  await page.getByRole('region', { name: 'Canvas projects' }).getByRole('button', { name: /Holiday Ideas A visual itinerary/ }).click()
  await note(page).waitFor()
  return page
}

